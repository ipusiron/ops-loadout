// Generate the file:// fallback from the canonical JSON, without dependencies.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const index = JSON.parse(fs.readFileSync(path.join(root, 'presets/index.json'), 'utf8'));
const presets = Object.fromEntries(Object.entries(index.presets).map(([key, meta]) => [key, JSON.parse(fs.readFileSync(path.join(root, 'presets', meta.file), 'utf8'))]));
const output = '// Generated by scripts/build-presets.cjs from presets/*.json. Do not edit.\nwindow.LoadoutPresets = ' + JSON.stringify({index, presets}, null, 2).replace(/</g, '\\u003c') + ';\n';
const target = path.join(root, 'presets-bundle.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw Error('Preset bundle is stale');
} else fs.writeFileSync(target, output);
